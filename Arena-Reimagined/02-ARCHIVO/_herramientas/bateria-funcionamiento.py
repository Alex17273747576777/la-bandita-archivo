#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
bateria-funcionamiento.py — ETAPA 3 · nano-lote 3.1: batería estática formal (solo lectura).
Por envase: XML bien formado (ET + lxml) · ids únicos · 0 recursos externos (src/css) ·
0 fugas markdown en texto visible · sello del fuente INCRUSTADO y coincidente con el fuente
real · DOCTYPE/namespace xhtml · <title> presente · sin metadatos de generación (R-01).
Salida: veredicto por pieza + exit 1 si hay fallo. Determinística.
"""
import os, re, sys, hashlib
from xml.etree import ElementTree as ET
import lxml.etree

HERE = os.path.dirname(__file__)
CANON = os.path.join(HERE, "..", "..", "00-CANON")
ENV = os.path.join(CANON, "_envases-xhtml")
PIEZAS = [
    ("TRATADO",   "TRATADO.md",                               "TRATADO-envase-XHTML-2026-10-10.xhtml"),
    ("MANUAL",    "MANUAL-COMPLETO.md",                       "MANUAL-COMPLETO-envase-XHTML-2026-10-10.xhtml"),
    ("LECCIONES", "LECCIONES-ALEXIS.md",                      "LECCIONES-ALEXIS-envase-XHTML-2026-10-10.xhtml"),
    ("CIMIENTO", "CANON-CIMIENTO-V28sep.html",              "CANON-CIMIENTO-envase-XHTML-2026-10-10.xhtml"),
    ("COMPENDIO", "COMPENDIO-INTEGRAL-LibroE-V26sep.html",    "COMPENDIO-INTEGRAL-envase-XHTML-2026-10-10.xhtml"),
]
NS = "{http://www.w3.org/1999/xhtml}"

def main():
    total_fallos = 0
    print("═══ ETAPA 3 · 3.1 BATERÍA ESTÁTICA FORMAL (solo lectura) ═══")
    for k, src, env in PIEZAS:
        sb = open(os.path.join(CANON, src), "rb").read()
        eb = open(os.path.join(ENV, env), "rb").read()
        d = eb.decode("utf-8")
        sello = hashlib.sha256(sb).hexdigest()[:16]
        res = []
        def chk(cond, msg): res.append((bool(cond), msg))
        try: ET.fromstring(eb); chk(True, "XML bien formado (ET)")
        except Exception as e: chk(False, "XML ET: %s" % e)
        try: lxml.etree.fromstring(eb); chk(True, "XML bien formado (lxml)")
        except Exception as e: chk(False, "XML lxml: %s" % e)
        ids = re.findall(r'id="([^"]+)"', d)
        chk(len(ids) == len(set(ids)), "ids únicos (%d)" % len(ids))
        chk(not re.search(r'\ssrc="https?:', d), "0 recursos externos src")
        chk(not re.search(r"@import|url\(\s*['\"]?https?:", d), "0 recursos externos css")
        chk('xmlns="http://www.w3.org/1999/xhtml"' in d, "namespace xhtml")
        chk(d.lstrip().startswith("<?xml"), "declaración XML")
        chk("<title>" in d and "Canon La Bandita" in d, "<title> presente")
        chk(sello in d, "sello del fuente incrustado (%s)" % sello)
        SKIP = {NS + "pre", NS + "code", NS + "style", NS + "script"}
        parts = []
        def walk(e):
            if e.tag in SKIP: return
            if e.text: parts.append(e.text)
            for ch in e:
                walk(ch)
                if ch.tail: parts.append(ch.tail)
        try:
            walk(ET.fromstring(eb))
            texto = " ".join(t.strip() for t in parts)
            fugas = re.findall(r"\*\*[^*]+\*\*|^#{1,6} ", texto, re.M)
            chk(not fugas, "0 fugas markdown%s" % ("" if not fugas else " %s" % fugas[:2]))
        except Exception:
            pass  # el check XML ya falló arriba
        low_col = ""
        m = re.search(r"<section[^>]*id=\"colofon\".*?</section>", d, re.S)
        if m: low_col = re.sub(r"<[^>]+>", " ", m.group(0)).lower()
        chk("generado por" not in low_col and "generated by" not in low_col, "R-01: sin metadatos de generación")
        fallos = [m2 for ok, m2 in res if not ok]
        total_fallos += len(fallos)
        print("— %-10s %2d/%2d %s" % (k, len(res) - len(fallos), len(res), "OK ✓" if not fallos else "FALLOS:"))
        for f in fallos: print("    ✗", f)
    print("VEREDICTO 3.1:", "5/5 piezas LIMPIAS ✓" if total_fallos == 0 else "%d FALLOS ✗" % total_fallos)
    sys.exit(1 if total_fallos else 0)

if __name__ == "__main__":
    main()
